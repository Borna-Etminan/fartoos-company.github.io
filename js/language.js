/*  LANGUAGE APPLICATION  */
function applyLanguage(language) {
    const selectedLanguage =
        translations[language] ? language : "fa";
    const elements =
        document.querySelectorAll("[data-i18n]");
    elements.forEach(element => {
        const key = element.getAttribute("data-i18n");
        if (
            translations[selectedLanguage] &&
            translations[selectedLanguage][key] !== undefined
        ) {
            element.textContent =
                translations[selectedLanguage][key];
        }
    });
    document.documentElement.lang = selectedLanguage;
    document.documentElement.dir =
        selectedLanguage === "fa"
            ? "rtl"
            : "ltr";
    document.body.dataset.language =
        selectedLanguage;
   // Notify the map and other dynamic components about language changes
   window.dispatchEvent(
       new CustomEvent("fartoos:languagechange", {
           detail: { language: selectedLanguage }
       })
   );
    localStorage.setItem(
        "fartoos-language",
        selectedLanguage
    );
}





/*  LANGUAGE TOGGLE  */
function toggleLanguage() {
    const current =
        localStorage.getItem("fartoos-language") || "fa";
    const next =
        current === "fa"
            ? "en"
            : "fa";
    applyLanguage(next);
}





/*  INITIAL LANGUAGE  */
document.addEventListener("DOMContentLoaded", () => {
    const savedLanguage =
        localStorage.getItem("fartoos-language") || "fa";
    applyLanguage(savedLanguage);
    const languageButton =
        document.getElementById("languageToggle");
    if (languageButton) {
        languageButton.addEventListener(
            "click",
            toggleLanguage
        );
    }
});

